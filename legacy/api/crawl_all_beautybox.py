"""Collect the publicly listed Beauty Box catalog. Python 3.10+; pip install lxml.
No proxy, VPN, login, CAPTCHA bypass or private data is used.
The public client API request format was inspected on 2026-11-16.
Live catalog access could NOT be validated in the authoring environment (geo 403).
"""
import argparse
import csv
import hashlib
import json
import re
import time
import urllib.error
import urllib.parse
import urllib.request
import urllib.robotparser
from datetime import datetime, timezone
from pathlib import Path
from lxml import html

SITE = 'https://beautybox.com.vn'
API = 'https://beautybox-api.hsv-tech.io/client'

class AccessBlocked(RuntimeError):
    pass

def now():
    return datetime.now(timezone.utc).isoformat()

def save(path, data):
    temp = path.with_suffix(path.suffix + '.tmp')
    temp.write_text(json.dumps(data,ensure_ascii=False,indent=2),encoding='utf-8')
    temp.replace(path)

def fetch(url, client_api=False):
    headers={'User-Agent':'BeautyBoxDatasetResearch/1.0','Accept-Language':'vi'}
    if client_api:
        # Normal request headers generated by Beauty Box's public storefront client.
        # They do not grant account access and cannot remove a country restriction.
        timestamp=str(int(time.time()*1000))
        headers.update({'timestamp':timestamp,'key':hashlib.md5((timestamp+'_ANHDEPTRAIVCL').encode()).hexdigest(),
                        'Origin':SITE,'Referer':SITE+'/'})
    for attempt in range(3):
        try:
            req=urllib.request.Request(url,headers=headers)
            with urllib.request.urlopen(req,timeout=40) as response:
                body=response.read().decode('utf-8')
                return json.loads(body) if client_api else body
        except urllib.error.HTTPError as exc:
            if exc.code in (401,403):
                message=exc.read().decode('utf-8',errors='replace')
                reason='country restriction' if 'block access from your country' in message else 'access denied'
                raise AccessBlocked(f'HTTP {exc.code}: {reason}. Stop; no automatic workaround.') from exc
            if exc.code==429:
                raise AccessBlocked('HTTP 429: rate limited; stop this run.') from exc
            if exc.code not in (500,502,503,504) or attempt==2:raise
        except (urllib.error.URLError,TimeoutError):
            if attempt==2:raise
        time.sleep(2**(attempt+1))
    raise RuntimeError('Request did not complete')

def text_from_html(markup):
    doc=html.fragment_fromstring(markup or '<p></p>',create_parent='div')
    for e in doc.xpath('.//script|.//style|.//noscript'):e.drop_tree()
    for e in doc.iter():
        if e.text:e.text=re.sub(r'\s+',' ',e.text)
        if e.tail:e.tail=re.sub(r'\s+',' ',e.tail)
    for e in doc.xpath('.//p|.//li|.//h1|.//h2|.//h3|.//h4|.//div|.//br'):
        e.tail='\n'+(e.tail or '')
    return '\n'.join(x.strip() for x in doc.text_content().splitlines() if x.strip())

def extract_labeled(text, label):
    lines=text.splitlines()
    for i,line in enumerate(lines):
        match=re.match(label+r'\s*(?::|$)',line,re.I)
        if match:
            return line[match.end():].strip() or (lines[i+1] if i+1<len(lines) else None)
    return None

def parse_product(markup, url):
    tree=html.fromstring(markup)
    nodes=tree.xpath('//script[@id="__NEXT_DATA__"]/text()')
    if not nodes:raise ValueError('Missing public __NEXT_DATA__; website structure changed')
    state=json.loads(nodes[0])['props']['pageProps']['initialReduxState']
    queries=state.get('productsApi',{}).get('queries',{})
    product=next((q['data'] for k,q in queries.items() if k.startswith('getByIdProducts(') and isinstance(q.get('data'),dict)),None)
    if not product or not product.get('id'):raise ValueError('No product object in this page')
    details=product.get('detail') or []
    vi=next((d for d in details if d.get('langCode')=='vi'),details[0] if details else {})
    description=text_from_html(vi.get('htmlDescription'))
    label=lambda pattern:extract_labeled(description,pattern)
    brand_elements=tree.xpath('//*[contains(concat(" ",normalize-space(@class)," ")," brand-name ")]')
    brand=next((e.text_content().strip() for e in brand_elements if e.text_content().strip()),None)
    name=vi.get('name') or (product.get('graphData') or {}).get('title')
    sizes=re.findall(r'(?<!\d)(\d+(?:[.,]\d+)?)\s*(ml|g|kg|l)\b',name or '',re.I)
    row={
        'product_id':str(product['id']),'sku':product.get('sku'),'name':name,
        'brand_explicit':brand,'category_slug':(product.get('productType') or {}).get('slug'),
        'origin_label_raw':(product.get('graphData') or {}).get('origin'),
        'brand_origin_explicit':label(r'(?:Xuất xứ thương hiệu|Nguồn gốc thương hiệu)'),
        'manufactured_in_explicit':label(r'(?:Sản xuất tại|Nơi sản xuất|Xuất xứ sản phẩm)'),
        'size_from_name':sizes,'current_price_vnd':product.get('currentPrice'),
        'min_price_vnd':product.get('minPrice'),'max_price_vnd':product.get('maxPrice'),
        'min_price_before_discount_vnd':product.get('minPriceBeforeDiscount'),
        'max_price_before_discount_vnd':product.get('maxPriceBeforeDiscount'),
        'benefits_labeled':label(r'(?:Công dụng(?: chính)?|Ưu điểm(?: nổi bật)?(?: của [^:]+)?)'),
        'ingredients_highlighted_labeled':label(r'Thành phần(?: chính| nổi bật| nổi trội)?'),
        'ingredients_full_labeled':label(r'(?:Thành phần đầy đủ|Full ingredients|Ingredients)'),
        'target_skin_or_hair_labeled':label(r'(?:Loại da(?: phù hợp| sử dụng)?|Làn da sử dụng|Loại tóc phù hợp|Đối tượng sử dụng)'),
        'usage_labeled':label(r'(?:Hướng dẫn sử dụng|Cách sử dụng|Cách dùng)'),
        'description_text':description,
        'image_paths_raw':[m.get('url') for m in product.get('medias',[]) if m.get('url')],
        'image_urls_from_html':list(dict.fromkeys(u for u in tree.xpath('//img/@src') if any((m.get('url') or '__none__') in u for m in product.get('medias',[])))),
        'variant_count':len(product.get('variants') or []),'is_active':product.get('isActive'),
        'stock_daily_raw':product.get('stockDaily'),'stock_pickup_daily_raw':product.get('stockPickupDaily'),
        'source_url':url,'fetched_at_utc':now(),
    }
    variants=[]
    for v in product.get('variants') or []:
        variants.append({'product_id':row['product_id'],'variant_id':str(v['id']),'sku':v.get('sku'),
                         'barcode_raw':v.get('barCode'),'price_vnd':v.get('price'),
                         'price_before_discount_vnd':v.get('priceBeforeDiscount'),
                         'attribute_values_raw':v.get('attributeValues'),
                         'stock_raw':v.get('stock'),'stock_pickup_raw':v.get('stockPickup'),
                         'is_active':v.get('isActive'),'source_url':url,'fetched_at_utc':row['fetched_at_utc']})
    return {'product':row,'variants':variants,'raw_product':product}

def export(out):
    snapshots=[]
    for f in sorted((out/'details').glob('*.json')):
        value=json.loads(f.read_text(encoding='utf-8'))
        if 'product' in value:snapshots.append(value)
    products=[s['product'] for s in snapshots]
    variants=[v for s in snapshots for v in s['variants']]
    for name,rows in [('products',products),('variants',variants)]:
        save(out/(name+'.json'),rows)
        if rows:
            with (out/(name+'.csv')).open('w',encoding='utf-8-sig',newline='') as stream:
                writer=csv.DictWriter(stream,fieldnames=list(rows[0]));writer.writeheader()
                for row in rows:writer.writerow({k:json.dumps(v,ensure_ascii=False) if isinstance(v,(list,dict)) else v for k,v in row.items()})
    return products,variants

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--output',default=None)
    parser.add_argument('--resume',action='store_true');parser.add_argument('--delay',type=float,default=1.5)
    args=parser.parse_args()
    if args.delay<1:parser.error('--delay must be at least 1 second')
    out=Path(args.output or ('beautybox_'+datetime.now().strftime('%Y%m%d_%H%M%S')))
    if out.exists() and any(out.iterdir()) and not args.resume:parser.error('Output exists. Use a new folder for fresh data, or --resume to continue.')
    out.mkdir(parents=True,exist_ok=True);(out/'details').mkdir(exist_ok=True)
    status={'started_at_utc':now(),'status':'incomplete','catalog_complete':False,'details_complete':False,
            'declared_total':None,'unique_catalog_products':0,'errors':[]}
    catalog_path=out/'catalog.json'
    try:
        robots=urllib.robotparser.RobotFileParser();robots.parse(fetch(SITE+'/robots.txt').splitlines())
        if not robots.can_fetch('BeautyBoxDatasetResearch',SITE+'/products'):raise AccessBlocked('robots.txt disallows catalog access')
        if args.resume and catalog_path.exists():
            catalog=json.loads(catalog_path.read_text(encoding='utf-8'))
            items=catalog['items'];status.update(catalog['status'])
        else:
            items=[];seen=set();offset=0;limit=40;declared=None
            while True:
                url=API+'/products?'+urllib.parse.urlencode({'limit':limit,'offset':offset})
                page=fetch(url,client_api=True)
                if not isinstance(page,dict) or not isinstance(page.get('data'),list) or 'total' not in page:raise ValueError('Unexpected catalog schema')
                total=int(page['total']);rows=page['data']
                if declared is None:declared=total
                elif total!=declared:raise ValueError(f'Catalog changed during pagination: {declared} -> {total}; rerun in a new folder')
                for product in rows:
                    pid=str(product.get('id',''))
                    if not pid:raise ValueError('Missing product ID in catalog')
                    if pid not in seen:items.append(product);seen.add(pid)
                status.update(declared_total=declared,unique_catalog_products=len(seen))
                save(out/'catalog_progress.json',{'items':items,'status':status})
                print(f'Catalog: {len(seen)}/{declared}',flush=True)
                offset+=len(rows)
                if offset>=declared or not rows:break
                time.sleep(args.delay)
            if declared==0:raise ValueError('Catalog returned zero. Not accepted as a complete Beauty Box dataset.')
            if len(items)!=declared:raise ValueError(f'Catalog incomplete or duplicate pages: {len(items)}/{declared}')
            status['catalog_complete']=True;save(catalog_path,{'items':items,'status':status})
        for i,item in enumerate(items,1):
            pid=str(item['id']);slug=item.get('slug')
            if not re.fullmatch(r'[A-Za-z0-9_-]+',pid):raise ValueError('Unexpected product ID')
            checkpoint=out/'details'/(pid+'.json')
            if args.resume and checkpoint.exists():continue
            if not slug:
                status['errors'].append({'product_id':pid,'error':'Missing slug'});continue
            url=SITE+'/products/'+urllib.parse.quote(str(slug),safe='-')
            if not robots.can_fetch('BeautyBoxDatasetResearch',url):raise AccessBlocked('robots.txt disallows '+url)
            try:
                snapshot=parse_product(fetch(url),url)
                if snapshot['product']['product_id']!=pid:raise ValueError('Catalog/detail ID mismatch')
                save(checkpoint,snapshot)
                print(f'Detail {i}/{len(items)}: '+snapshot['product']['name'],flush=True)
            except AccessBlocked:raise
            except Exception as exc:status['errors'].append({'product_id':pid,'url':url,'error':str(exc)})
            save(out/'status.json',status);time.sleep(args.delay)
    except KeyboardInterrupt:status['errors'].append({'error':'Interrupted by user; resume supported'})
    except Exception as exc:status['errors'].append({'error':str(exc)});print('STOP:',str(exc),flush=True)
    finally:
        products,variants=export(out)
        status.update(exported_products=len(products),exported_variants=len(variants),finished_at_utc=now())
        if catalog_path.exists():
            cat=json.loads(catalog_path.read_text(encoding='utf-8'))
            expected={str(x['id']) for x in cat['items']};actual={x['product_id'] for x in products}
            status['missing_product_ids']=sorted(expected-actual)
            status['details_complete']=bool(expected) and expected==actual
        if status['catalog_complete'] and status['details_complete']:status['status']='complete'
        save(out/'status.json',status)
        print(json.dumps(status,ensure_ascii=False,indent=2));print('Output:',out.resolve())

if __name__=='__main__':main()
